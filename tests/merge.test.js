'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const ctx={TextEncoder,TextDecoder,Uint8Array,ArrayBuffer,Uint16Array,Math};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('src/merge.js','utf8')+'\nthis.merge=NEXA_MERGE;',ctx);
const x=ctx.merge;
const base='title\nline A\nunchanged\nline B\nfooter\n';
const local='title\nline A edited on Windows\nunchanged\nline B\nfooter\n';
const remote='title\nline A\nunchanged\nline B edited on iPhone\nfooter\n';
const result=x.merge(base,local,remote);
assert.equal(result.ok,true);
assert.equal(result.text,'title\nline A edited on Windows\nunchanged\nline B edited on iPhone\nfooter\n');
assert.equal(x.merge(base,local,local).text,local);
const overlap=x.merge(base,local,'title\nline A edited on iPhone\nunchanged\nline B\nfooter\n');
assert.equal(overlap.ok,false);
assert.equal(overlap.reason,'TRECHOS_SOBREPOSTOS');
assert.equal(x.merge(base,'title\nline A\ninserted A\nunchanged\nline B\nfooter\n','title\nline A\ninserted B\nunchanged\nline B\nfooter\n').ok,false,'same insertion position conflicts');
assert.equal(x.merge(base,'title\nline A\nunchanged\nline B\nfooter\nWindows\n',remote).ok,true);
assert.equal(x.merge('á\nβ\nγ\n','á editado\nβ\nγ\n','á\nβ\nγ editado\n').ok,true);
assert.throws(()=>x.decode(Uint8Array.of(255,254)),/encoded|valid|UTF|utf|decode/i);
assert.throws(()=>x.decode(Uint8Array.of(0)),/CONTEUDO_NAO_TEXTUAL/);
assert.equal(x.merge('a','a','a'.repeat(300000)).ok,false);
console.log('PASS merge: mudanças disjuntas, conflito de linhas, inserções, Unicode, limites UTF-8');
