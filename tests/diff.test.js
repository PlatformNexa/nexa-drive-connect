'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const context={Uint16Array,Array,Math};vm.createContext(context);
vm.runInContext(fs.readFileSync('src/diff.js','utf8')+';this.diff=NEXA_DIFF;',context);
const d=context.diff;
const equal=d.compare('a\nb\nc','a\nb\nc');
assert.equal(equal.available,true);assert.equal(equal.changes,0);
assert.equal(Array.from(equal.rows,r=>r.left.type).join(','),'same,same,same');
const modified=d.compare('a\nLED 3000K\nfinal','a\nLED 4000K\nfinal');
assert.equal(modified.changes,1);assert.equal(modified.rows[1].left.type,'modified');
assert.equal(modified.rows[1].right.type,'modified');
const added=d.compare('a\nfinal','a\nextra\nfinal');
assert.equal(added.changes,1);assert.equal(added.rows[1].left,null);
assert.equal(added.rows[1].right.type,'added');
const removed=d.compare('a\nextra\nfinal','a\nfinal');
assert.equal(removed.changes,1);assert.equal(removed.rows[1].right,null);
assert.equal(removed.rows[1].left.type,'removed');
const unicode=d.compare('ação\nárvore','ação\nÁrvore');
assert.equal(unicode.changes,1);
assert.equal(d.compare('x\n'.repeat(400),'x').available,false);
assert.equal(d.compare('x'.repeat(90001),'x').available,false);
assert.equal(d.compare(null,'hello').available,false);
assert.equal(d.compare('','').changes,0);
console.log('PASS UI diff: equal/added/removed/modified, UTF-8 text, safety bounds');
